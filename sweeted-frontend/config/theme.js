export function getTheme(paletteId = 'emerald', isDark = false) {
  const palette = PALETTES[paletteId] || PALETTES.emerald;
  const active = isDark ? palette.dark : palette.light;
  // Onyx sombre : primary quasi-blanc -> texte sur primary doit être noir
  if (paletteId === 'onyx' && isDark) {
    return { ...active, onPrimary: '#09090B' };
  }
  return active;
}

